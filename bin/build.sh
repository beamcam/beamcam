#!/bin/bash

# Build script: assembles dist/ from src/ and .env
#
#   - dist/config.js   public settings from .env (whitelist below; no secrets)
#   - dist/index.html  the app, or the landing page if src/pages/ exists
#                      (the app then lives at dist/app.html)
#   - JS, CSS, vendored libraries, PWA manifest
#
# No package manager, no bundler: bash and cp.

set -e
shopt -u patsub_replacement 2>/dev/null || true  # bash 5.2: keep "&" literal in \${x//a/b}

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
SRC_DIR="$PROJECT_ROOT/src"
DIST_DIR="$PROJECT_ROOT/dist"
ENV_FILE="${ENV_FILE:-$PROJECT_ROOT/.env}"

# ---------- .env (parsed, never executed) ----------
if [ ! -f "$ENV_FILE" ]; then
    echo "❌ $ENV_FILE not found. Start from the example: cp .env.example .env"
    exit 1
fi
while IFS= read -r line || [ -n "$line" ]; do
    line="${line%$'\r'}"
    [[ "$line" =~ ^[[:space:]]*(#|$) ]] && continue
    [[ "$line" =~ ^[[:space:]]*([A-Z_][A-Z0-9_]*)=(.*)$ ]] || continue
    key="${BASH_REMATCH[1]}"
    val="${BASH_REMATCH[2]}"
    val="${val%%[[:space:]]#*}"                                   # trailing " # comment"
    val="${val#"${val%%[![:space:]]*}"}"; val="${val%"${val##*[![:space:]]}"}"  # trim
    [[ "$val" =~ ^\"(.*)\"$ || "$val" =~ ^\'(.*)\'$ ]] && val="${BASH_REMATCH[1]}"
    printf -v "$key" '%s' "$val"
done < "$ENV_FILE"

: "${APP_NAME:?APP_NAME is required in .env}"
: "${APP_DOMAIN:?APP_DOMAIN is required in .env}"
APP_THEME_COLOR="${APP_THEME_COLOR:-#6366f1}"
SIGNALING_HOST="${SIGNALING_HOST:-$APP_DOMAIN}"
SIGNALING_PORT="${SIGNALING_PORT:-443}"
SIGNALING_PATH="${SIGNALING_PATH:-/peerjs}"
SIGNALING_SECURE="${SIGNALING_SECURE-1}"   # unset = 1 (HTTPS/WSS); empty = plain, for localhost tests
TURN_HOST="${TURN_HOST:-$APP_DOMAIN}"
TURN_PORT="${TURN_PORT:-3478}"

flag() { [ -n "$1" ] && [ "$1" != "0" ] && echo true || echo false; }
json() { local s="${1//\\/\\\\}"; s="${s//\"/\\\"}"; printf '"%s"' "$s"; }
html() { local s="${1//&/&amp;}"; s="${s//</&lt;}"; s="${s//>/&gt;}"; s="${s//\"/&quot;}"; printf '%s' "$s"; }

APP_PAGE="index.html"   # the app lives at /; site pages (if any) around it
APP_HOME_URL="${APP_HOME_URL:-./}"
if [ -d "$SRC_DIR/pages/about" ]; then
    APP_ABOUT_URL="${APP_ABOUT_URL:-./about/}"   # where the status light links to
else
    APP_ABOUT_URL="${APP_ABOUT_URL:-$APP_HOME_URL}"
fi
if [ -d "$SRC_DIR/pages/a-propos" ]; then
    APP_ABOUT_URL_FR="${APP_ABOUT_URL_FR:-./a-propos/}"   # same, for French readers
else
    APP_ABOUT_URL_FR="${APP_ABOUT_URL_FR:-$APP_ABOUT_URL}"
fi

# Build number: shown on the home screen, and appended to every asset URL so
# browsers (iOS above all) can't keep serving the previous script or styles
APP_VERSION="$(date -u +%Y.%m.%d-%H%M)"

echo "🔨 Building $APP_NAME $APP_VERSION"
echo "   Source: $SRC_DIR"
echo "   Output: $DIST_DIR"
echo "   Apps:   live=$(flag "$APP_LIVE") videocall=$(flag "$APP_VIDEOCALL") audiocall=$(flag "$APP_AUDIOCALL") editor=$(flag "$APP_EDITOR")"
echo ""

mkdir -p "$DIST_DIR"

# ---------- public config ----------
cat > "$DIST_DIR/config.js" << EOF
// Generated by bin/build.sh from .env - do not edit, rebuild instead.
window.APP_CONFIG = {
	name: $(json "$APP_NAME"),
	version: $(json "$APP_VERSION"),
	signaling: { host: $(json "$SIGNALING_HOST"), port: $SIGNALING_PORT, path: $(json "$SIGNALING_PATH"), secure: $(flag "$SIGNALING_SECURE") },
	stun: $(json "stun:$TURN_HOST:$TURN_PORT"),
	apps: {
		live: $(flag "$APP_LIVE"),
		videocall: $(flag "$APP_VIDEOCALL"),
		audiocall: $(flag "$APP_AUDIOCALL"),
		editor: $(flag "$APP_EDITOR")
	}
};
EOF

# ---------- static files ----------
echo "📦 Copying assets..."
cp "$SRC_DIR/script.js" "$SRC_DIR/style.css" "$DIST_DIR/"
[ -f "$SRC_DIR/sw.js" ] && cp "$SRC_DIR/sw.js" "$DIST_DIR/"
[ -f "$SRC_DIR/site.css" ] && cp "$SRC_DIR/site.css" "$DIST_DIR/"
FONT_LINKS=''
if [ -d "$SRC_DIR/fonts" ]; then
    mkdir -p "$DIST_DIR/fonts"
    cp "$SRC_DIR/fonts/"*.woff2 "$DIST_DIR/fonts/"
    # the text faces the home screen paints first
    FONT_LINKS='<link rel="preload" href="./fonts/poppins-400.woff2" as="font" type="font/woff2" crossorigin>
    <link rel="preload" href="./fonts/poppins-600.woff2" as="font" type="font/woff2" crossorigin>'
fi
if [ -d "$SRC_DIR/assets" ]; then
    mkdir -p "$DIST_DIR/assets"
    cp "$SRC_DIR/assets/"*.js "$DIST_DIR/assets/"
fi

# Icons (optional): src/icons/ comes from bin/make-icons.sh. Without it the app
# falls back to a generic inline SVG icon.
if [ -d "$SRC_DIR/icons" ]; then
    echo "🎨 Copying icons..."
    mkdir -p "$DIST_DIR/icons"
    cp "$SRC_DIR/icons/"*.svg "$SRC_DIR/icons/"*.png "$DIST_DIR/icons/"
    # Browsers and iOS look for these two at the root without being told
    cp "$SRC_DIR/icons/favicon.ico" "$SRC_DIR/icons/apple-touch-icon.png" "$DIST_DIR/"
    ICON_LINKS='<link rel="icon" href="./favicon.ico" sizes="32x32">
    <link rel="icon" href="./icons/icon.svg" type="image/svg+xml">
    <link rel="apple-touch-icon" href="./apple-touch-icon.png">'
    MANIFEST_ICONS='{ "src": "./icons/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any" },
    { "src": "./icons/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any" },
    { "src": "./icons/icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable" }'
else
    ICON_LINKS=''
    MANIFEST_ICONS='{
      "src": "data:image/svg+xml,<svg xmlns='"'"'http://www.w3.org/2000/svg'"'"' viewBox='"'"'0 0 100 100'"'"'><rect width='"'"'100'"'"' height='"'"'100'"'"' fill='"'"'%236366f1'"'"'/><circle cx='"'"'50'"'"' cy='"'"'40'"'"' r='"'"'20'"'"' fill='"'"'white'"'"'/><rect x='"'"'30'"'"' y='"'"'60'"'"' width='"'"'40'"'"' height='"'"'25'"'"' rx='"'"'5'"'"' fill='"'"'white'"'"'/></svg>",
      "sizes": "512x512",
      "type": "image/svg+xml",
      "purpose": "any maskable"
    }'
fi

# Link previews for shared app links (/#cam-…), when the site ships a share image
OG_TAGS=''
if [ -f "$SRC_DIR/pages/og-image.jpg" ]; then
    OG_TAGS="<meta property=\"og:title\" content=\"$(html "$APP_NAME")\">
    <meta property=\"og:description\" content=\"Live camera or call, peer-to-peer in the browser. No app, no account.\">
    <meta property=\"og:image\" content=\"https://$(html "$APP_DOMAIN")/og-image.jpg\">
    <meta name=\"twitter:card\" content=\"summary_large_image\">"
fi

if [ -d "$SRC_DIR/pages" ]; then
    echo "📄 Copying site pages..."
    cp -R "$SRC_DIR/pages/." "$DIST_DIR/"
    # The app used to live at /app.html: old links and QR codes land on /
    cat > "$DIST_DIR/app.html" << 'EOF'
<!DOCTYPE html>
<meta charset="UTF-8">
<meta name="robots" content="noindex">
<script>location.replace("./" + location.hash);</script>
<a href="./">Open the app</a>
EOF
fi

# ---------- app page ----------
echo "📄 Building $APP_PAGE..."
NAME_HTML="$(html "$APP_NAME")"

cat > "$DIST_DIR/$APP_PAGE" << EOF
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0, maximum-scale=1.0, user-scalable=no, viewport-fit=cover">
    <title>$NAME_HTML</title>
    <meta name="description" content="Phone camera, viewer, 1-to-1 calls and local recorder. Peer-to-peer WebRTC in the browser.">

    <!-- PWA Meta Tags -->
    <meta name="theme-color" content="$(html "$APP_THEME_COLOR")">
    <meta name="mobile-web-app-capable" content="yes">
    <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
    <meta name="apple-mobile-web-app-title" content="$NAME_HTML">

    <link rel="manifest" href="./manifest.json?v=$APP_VERSION">
    $ICON_LINKS
    $FONT_LINKS
    $OG_TAGS
    <link rel="stylesheet" href="./style.css?v=$APP_VERSION">

    <!-- Vendored libraries: served from this host, no CDN -->
    <script src="./assets/peerjs.min.js?v=$APP_VERSION"></script>
    <script src="./assets/qrcode.min.js?v=$APP_VERSION"></script>
    <script src="./assets/lucide.min.js?v=$APP_VERSION"></script>
    <script src="./config.js?v=$APP_VERSION"></script>
</head>
<body>
EOF

# The fragment's {{PLACEHOLDERS}}; values HTML-escaped, then made sed-safe
sed_safe() { printf '%s' "$1" | sed 's/[\/&|]/\\&/g'; }
sed -e "s|{{APP_NAME}}|$(sed_safe "$NAME_HTML")|g" \
    -e "s|{{APP_HOME_URL}}|$(sed_safe "$(html "$APP_HOME_URL")")|g" \
    -e "s|{{APP_ABOUT_URL}}|$(sed_safe "$(html "$APP_ABOUT_URL")")|g" \
    -e "s|{{APP_ABOUT_URL_FR}}|$(sed_safe "$(html "$APP_ABOUT_URL_FR")")|g" \
    "$SRC_DIR/app.html" >> "$DIST_DIR/$APP_PAGE"

cat >> "$DIST_DIR/$APP_PAGE" << EOF

<!-- Application Script -->
<script src="./script.js?v=$APP_VERSION"></script>
</body>
</html>
EOF

# Polled by the app (no-store) to notice a newer build
printf '{"version":%s}\n' "$(json "$APP_VERSION")" > "$DIST_DIR/version.json"

# ---------- PWA manifest ----------
echo "📱 Creating manifest.json..."
cat > "$DIST_DIR/manifest.json" << EOF
{
  "name": $(json "$APP_NAME"),
  "short_name": $(json "$APP_NAME"),
  "description": "Phone camera, viewer, 1-to-1 calls and local recorder over peer-to-peer WebRTC",
  "start_url": "./",
  "display": "standalone",
  "background_color": "#050505",
  "theme_color": $(json "$APP_THEME_COLOR"),
  "orientation": "any",
  "icons": [
    $MANIFEST_ICONS
  ],
  "categories": ["utilities", "photo", "video"]
}
EOF

echo ""
echo "✅ Build complete: $DIST_DIR"
echo ""
echo "🚀 Test locally (camera access needs HTTPS or localhost):"
echo "   cd $DIST_DIR && python3 -m http.server 8000   ->  http://localhost:8000/$APP_PAGE"
